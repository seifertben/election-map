// Derive each House district's 2024 presidential two-party margin for the
// House map's 2024-baseline / swing control, from committed data only.
//
//   node scripts/build-house-2024.mjs
//
// Sources:
//   scripts/party/pres_by_cd.csv   The Downballot's 2024 presidential results
//       for every district on the 2026 (120th Congress) lines: the Harris and
//       Trump two-party vote shares.
//
// The emitted margin is Democratic minus Republican in percentage points
// (positive is a Democratic win), so adding a uniform swing in points and
// reading the sign gives the swung winner. The script writes src/data/house2024.ts.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PRES_PATH = resolve(__dirname, "party/pres_by_cd.csv");
const OUT_PATH = resolve(__dirname, "../src/data/house2024.ts");

const ABBR_TO_FIPS = {
  AL: "01", AK: "02", AZ: "04", AR: "05", CA: "06", CO: "08", CT: "09",
  DE: "10", DC: "11", FL: "12", GA: "13", HI: "15", ID: "16", IL: "17",
  IN: "18", IA: "19", KS: "20", KY: "21", LA: "22", ME: "23", MD: "24",
  MA: "25", MI: "26", MN: "27", MS: "28", MO: "29", MT: "30", NE: "31",
  NV: "32", NH: "33", NJ: "34", NM: "35", NY: "36", NC: "37", ND: "38",
  OH: "39", OK: "40", OR: "41", PA: "42", RI: "44", SC: "45", SD: "46",
  TN: "47", TX: "48", UT: "49", VT: "50", VA: "51", WA: "53", WV: "54",
  WI: "55", WY: "56",
};

const pad2 = (n) => String(n).padStart(2, "0");
const round = (x) => Math.round(x * 100) / 100;

async function main() {
  const text = await readFile(PRES_PATH, "utf8");
  const lines = text.split(/\r?\n/);
  const header = lines.findIndex((l) => l.startsWith("District,"));
  if (header < 0) throw new Error(`no District header in ${PRES_PATH}`);

  const margins = {};
  for (const line of lines.slice(header + 2)) {
    const parts = line.split(",");
    if (parts.length < 5) continue;
    const m = /^([A-Z]{2})-(AL|\d{2})$/.exec(parts[0]);
    if (!m) continue;
    const fips = ABBR_TO_FIPS[m[1]];
    if (!fips) continue;
    const district = m[2] === "AL" ? "00" : pad2(Number(m[2]));
    const geoid = `${fips}${district}`;
    const harris = Number(parts[3]);
    const trump = Number(parts[4]);
    if (!(harris + trump > 0)) continue;
    margins[geoid] = round(((harris - trump) / (harris + trump)) * 100);
  }

  const entries = Object.entries(margins).sort((a, b) =>
    a[0].localeCompare(b[0]),
  );
  const body = entries
    .map(([geoid, margin]) => `  "${geoid}": ${margin},`)
    .join("\n");

  const out = `/**
 * Each House district's 2024 presidential two-party margin, in percentage
 * points (positive is Democratic), for the House map's 2024-baseline and
 * uniform-swing control. Generated by scripts/build-house-2024.mjs
 * (npm run build:house-2024) from The Downballot's 2024 presidential results
 * by district (scripts/party/pres_by_cd.csv) on the 120th Congress lines.
 *
 * Keyed by the four-digit district geoid used by cd120.json (state FIPS +
 * two-digit district number; "00" for at-large seats).
 */
export const HOUSE_2024_MARGIN: Record<string, number> = {
${body}
};
`;
  await writeFile(OUT_PATH, out);
  console.log(
    `Wrote ${entries.length} districts to ${OUT_PATH} ` +
      `(${entries.filter(([, v]) => v > 0).length} D, ` +
      `${entries.filter(([, v]) => v < 0).length} R)`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
