// Derive each state's 2024 presidential partisan lean for the State Analyzer's
// no-poll baseline, from committed data only.
//
//   node scripts/build-state-lean.mjs
//
// Sources:
//   scripts/party/pres_by_cd.csv   The Downballot's 2024 presidential results
//       for every district on the 2026 (120th Congress) lines: the Harris and
//       Trump two-party vote shares.
//   public/data/demographics.json  District voting-age populations, used to
//       weight the districts into a state total (the Downballot table carries
//       no vote counts).
//
// A state's lean is its voting-age-population-weighted Democratic two-party
// presidential share minus the national two-party share, so 0 is a state that
// voted exactly like the country. The script emits src/data/stateLean.ts, which
// the analyzer shifts its national exit-poll baseline by.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PRES_PATH = resolve(__dirname, "party/pres_by_cd.csv");
const DEMO_PATH = resolve(__dirname, "../public/data/demographics.json");
const OUT_PATH = resolve(__dirname, "../src/data/stateLean.ts");

/** National 2024 two-party presidential Democratic share: Harris 75,017,613 of
 *  the 152,320,193 two-party votes (mirrors build-party.mjs). */
const PRES_2024_NATIONAL_D = 0.4925;

const ABBR_TO_FIPS = {
  AL: "01", AK: "02", AZ: "04", AR: "05", CA: "06", CO: "08", CT: "09",
  DE: "10", DC: "11", FL: "12", GA: "13", HI: "15", ID: "16", IL: "17",
  IN: "18", IA: "19", KS: "20", KY: "21", LA: "22", ME: "23", MD: "24",
  MA: "25", MI: "26", MN: "27", MS: "28", MO: "29", MT: "30", NE: "31",
  NV: "32", NH: "33", NJ: "34", NM: "35", NY: "36", NC: "37", ND: "38",
  OH: "39", OK: "40", OR: "41", PA: "42", RI: "44", SC: "45", SD: "46",
  TN: "47", TX: "48", UT: "49", VT: "50", VA: "51", WA: "53", WV: "54",
  WI: "55", WY: "56",
};

const pad2 = (n) => String(n).padStart(2, "0");
const round = (x) => Math.round(x * 10000) / 10000;

async function main() {
  const text = await readFile(PRES_PATH, "utf8");
  const demo = JSON.parse(await readFile(DEMO_PATH, "utf8"));
  const lines = text.split(/\r?\n/);
  const header = lines.findIndex((l) => l.startsWith("District,"));
  if (header < 0) throw new Error(`no District header in ${PRES_PATH}`);

  const acc = {};
  let nationalNum = 0;
  let nationalDen = 0;
  let matched = 0;
  let unmatched = 0;

  for (const line of lines.slice(header + 2)) {
    const parts = line.split(",");
    if (parts.length < 5) continue;
    const m = /^([A-Z]{2})-(AL|\d{2})$/.exec(parts[0]);
    if (!m) continue;
    const fips = ABBR_TO_FIPS[m[1]];
    if (!fips) continue;
    const district = m[2] === "AL" ? "00" : pad2(Number(m[2]));
    const geoid = `${fips}${district}`;
    const harris = Number(parts[3]);
    const trump = Number(parts[4]);
    if (!(harris + trump > 0)) continue;
    const share = harris / (harris + trump);
    const vap = demo.districts[geoid]?.votingAgePopulation;
    const weight = vap > 0 ? vap : 1;
    if (!(vap > 0)) unmatched += 1;
    else matched += 1;
    const a = (acc[fips] ??= { num: 0, den: 0 });
    a.num += weight * share;
    a.den += weight;
    nationalNum += weight * share;
    nationalDen += weight;
  }

  const weightedMean = nationalDen > 0 ? nationalNum / nationalDen : PRES_2024_NATIONAL_D;
  const entries = Object.entries(acc)
    .map(([fips, a]) => [
      fips,
      round(a.den > 0 ? a.num / a.den - PRES_2024_NATIONAL_D : 0),
    ])
    .sort((x, y) => x[0].localeCompare(y[0]));

  const body = entries
    .map(([fips, lean]) => `  "${fips}": ${lean},`)
    .join("\n");

  const out = `/**
 * Per-state 2024 presidential partisan lean for the State Analyzer's no-poll
 * baseline. Generated by scripts/build-state-lean.mjs (npm run build:state-lean)
 * from The Downballot's 2024 presidential results by district
 * (scripts/party/pres_by_cd.csv), weighted by district voting-age population
 * from public/data/demographics.json. Each value is the state's Democratic
 * two-party presidential share minus the national share (${PRES_2024_NATIONAL_D});
 * 0 is a state that voted exactly like the country.
 */
export const STATE_LEAN: Record<string, number> = {
${body}
};
`;
  await writeFile(OUT_PATH, out);
  console.log(
    `VAP-weighted district mean: ${weightedMean.toFixed(4)} (national vote share ` +
      `${PRES_2024_NATIONAL_D}); wrote ${entries.length} states ` +
      `(${matched} districts weighted by VAP, ${unmatched} unweighted) to ${OUT_PATH}`,
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
